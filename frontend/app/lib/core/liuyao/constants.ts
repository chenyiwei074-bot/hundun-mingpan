/** 根据宫五行和爻地支五行返回六亲 */
export function getLiuQin(gongWx: WuXing, zhiWx: WuXing): LiuQin {
  if (gongWx === zhiWx) return '兄弟';
  if (WUXING_SHENGWO[gongWx] === zhiWx) return '父母';
  if (WUXING_KEWO[gongWx] === zhiWx) return '官鬼';
  if (WUXING_KE[gongWx] === zhiWx) return '妻财';
  return '子孙';
}

