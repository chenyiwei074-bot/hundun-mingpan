// 合盘（两人对照）的输入输出契约。
//
// 三条硬边界，都是裁定定下来的：
//  1. 不出分。没有吉凶分、没有匹配度百分比、没有"合适/不合适"的结论。
//     能出的只有"两张盘各自是什么"以及"这两个落点之间存不存在某个关系"。
//  2. 不引古籍。docs/classics 里没有任何合婚原文（只有滴天髓六亲、三命通会卷五、
//     渊海子平伤官），原典之外不发明 —— 所以整节标「自研 · 非还原」。
//  3. 对方生辰只活在这台设备上：不进 API、不进报告、不进回执、不进台账、不上链。

export const HEPAN_BASIS = 'hepan-local-v1';

export interface HepanPartyMeta {
  /** 用户自己写的称呼，不是真名，也不参与任何计算，只用于回显。 */
  称呼: string;
  性别: '男' | '女';
  /** 展示用的原始输入串（换算前），让用户能核对自己填了什么。 */
  原始输入: string;
}

export interface HepanItem {
  /** 立项名，例如「日主相待」。 */
  立项: string;
  /** 观察：只陈述两张盘上读得到的事实与它们之间的关系。 */
  观察: string;
  /** 这条观察是从哪几个盘面字段读出来的（上屏，让用户能核）。 */
  依据: string[];
  /** 这条观察说不准的地方 —— 缺了现场、缺了第三方、或者粒度不够。 */
  不确定项: string[];
}

export interface HepanReport {
  输入摘要: string[];
  项目: HepanItem[];
  /** 明确没做的事与缺的输入。不写就等于让用户以为藏在别处。 */
  未出: string[];
  口径戳: string;
}

/** 合盘永远不产出的东西，写成常量供套件反向断言。 */
export const HEPAN_FORBIDDEN = ['评分', '匹配度', '百分比', '吉', '凶', '宜忌', '化煞', '相克必分'] as const;
