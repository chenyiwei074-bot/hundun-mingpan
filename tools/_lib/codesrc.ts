// 验收套件的公共件：**任何拿产品源码文本做判定的闸门，先剥注释再比**。
//
// 为什么这要写成一个共享件而不是各套件自己 copy 一行 replace：
// 2026-10-21 一天内被自己的注释咬了两次 ——
// ① tst 的同步表 forbid 命中了 ops 照搬时保留的说明注释「原来 return '海中金'」，
//   三份已同步的文件报成 PENDING（假红）；
// ② kline 的引用扫描把 tools/tst-acceptance 里"server 别留 runZiweiTests"那句话当成调用点（假红）。
// 假红只是吵；**假绿才贵**：一条"必须出现 X"的正向断言，X 只写在注释里也能绿，
// 于是那一格代码早没了，闸门还在替它说话。
//
// 两个粒度：
//  - stripComments：剥 // 与 /* */。判定"这行代码在不在"用它。
//  - stripLiterals：再剥字符串/模板字面量。判定"这个标识符有没有被引用"用它 ——
//    字符串里提到一个函数名不是引用（`href:'/'` 白名单、reason 文案都是这一类）。
// 用法上不要"顺手"用更宽的那个：剥了字面量之后再判"页面里必须出现某句文案"会判不出，
// 那句文案本来就是字符串。

/** 剥掉 `//` 行注释与 `/* *\/` 块注释（含 JSDoc）。 */
export function stripComments(s: string): string {
  return s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
}

/** 在剥注释之上再剥字符串/模板字面量与正则字面量的内容，只留代码骨架。 */
export function stripLiterals(s: string): string {
  return stripComments(s)
    .replace(/'[^'\n]*'|"[^"\n]*"|`[\s\S]*?`/g, "''")
    // 正则字面量：只认出现在 = ( , : 之后的那种，避免把除号当成正则开头。
    .replace(/(?:^|[=(:,]\s*)\/(?:\\.|\[[^\]]*\]|[^/\n])+\/[gimsuy]*/g, "$1/''");
}
